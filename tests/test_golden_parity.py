"""The Python reference reproduces the golden data that the Kotlin tests consume.

``android/app/src/test/resources/olcum_altin_veri.csv`` is generated by
``scripts/23_altin_veri.py`` from the Python reference and is the oracle for
``OlcumTest.kt``. Re-checking it here closes the loop in CI: if someone edits
the reference (or the CSV) so that the two sides could drift apart, this fails
even though no Android toolchain is involved.
"""

import csv
import importlib.util

import pytest

TOLERANCE = 1e-6  # the CSV stores 10 decimals


@pytest.fixture(scope="module")
def reference(root):
    path = root / "scripts" / "19_kilavuz_cizim.py"
    spec = importlib.util.spec_from_file_location("kilavuz_cizim", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def rows(root):
    path = root / "android" / "app" / "src" / "test" / "resources" / "olcum_altin_veri.csv"
    lines = [ln for ln in path.read_text(encoding="utf-8").splitlines() if not ln.startswith("#")]
    return list(csv.DictReader(lines))


def _float(cell: str) -> float:
    return float(cell) if cell not in ("", None) else 0.0


def test_every_row_kind_is_covered(rows):
    # A new kind of row must come with a check below, not slip through silently.
    assert {r["tip"] for r in rows} == {"aci", "durus"}


def test_axillary_angle_matches_golden(reference, rows):
    cases = [r for r in rows if r["tip"] == "aci"]
    assert cases
    for r in cases:
        got = reference.aksiller_aci(
            (_float(r["a"]), _float(r["b"])), (_float(r["c"]), _float(r["d"])), _float(r["e"])
        )
        assert got == pytest.approx(_float(r["beklenen1"]), abs=TOLERANCE), r


def test_roll_and_pitch_match_golden(reference, rows):
    cases = [r for r in rows if r["tip"] == "durus"]
    assert cases
    for r in cases:
        gx, gy, gz = _float(r["a"]), _float(r["b"]), _float(r["c"])
        assert reference.roll_acisi(gx, gy) == pytest.approx(_float(r["beklenen1"]), abs=TOLERANCE)
        assert reference.pitch_acisi(gx, gy, gz) == pytest.approx(
            _float(r["beklenen2"]), abs=TOLERANCE
        )


def test_sign_convention_right_shoulder_high_is_positive(reference):
    # Right armpit (x=300) higher on screen (smaller y) than the left one (x=700).
    assert reference.aksiller_aci((300, 460), (700, 500)) > 0
    assert reference.aksiller_aci((300, 500), (700, 460)) < 0
    # A phone rolled by the same angle cancels the tilt.
    assert reference.aksiller_aci((300, 500), (700, 500), 6.0) == pytest.approx(-6.0)


def test_pitch_gate_threshold(reference):
    assert reference.guven_kontrolu(8.0) is True
    assert reference.guven_kontrolu(8.01) is False
    assert reference.guven_kontrolu(-8.01) is False
